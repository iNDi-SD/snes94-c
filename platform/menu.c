#define CW PM_MENU_CELL_W

/* ---- the drawing --------------------------------------------------------------------------- */

static void put(uint32_t *px, int w, int h, int pitch, int x, int y, uint32_t rgb)
{
    if (x >= 0 && y >= 0 && x < w && y < h) px[y * pitch + x] = rgb;
}

static int glyphs(uint32_t *px, int w, int h, int pitch, int x, int y, const char *s, uint32_t rgb)
{
    for (; *s; s++, x += CW) {
        unsigned c = (uint8_t)*s;
        const uint8_t *g = font[c >= 32 && c < 32 + 98 ? c - 32 : '?' - 32];
        for (int r = 0; r < 8; r++)
            for (int b = 0; b < 5; b++)
                if (g[r] >> (4 - b) & 1) put(px, w, h, pitch, x + b, y + r, rgb);
    }
    return x;
}

int pm_menu_text(uint32_t *px, int w, int h, int pitch, int x, int y, const char *s, uint32_t rgb)
{
    glyphs(px, w, h, pitch, x + 1, y + 1, s, 0);         /* (a shadow, for any picture under it) */
    return glyphs(px, w, h, pitch, x, y, s, rgb);
}

/* ---- the settings menu --------------------------------------------------------------------- */

#define SHADE 0xC0000000u                                /* (the picture darkened under the menu, as the setup screen does) */
#define WHITE 0xFFFFFF
#define DIM 0x9090A0
#define GOLD 0xFFD84A

static void line(uint32_t *px, int w, int h, int pitch, int row, const char *s, uint32_t rgb)
{
    pm_menu_text(px, w, h, pitch, 4, 4 + row * PM_MENU_CELL_H, s, rgb);
}

void pm_menu_settings_draw(uint32_t *px, int w, int h, int pitch, const pm_menu_settings_view *v)
{
    for (int y = 0; y < h; y++)
        for (int x = 0; x < w; x++) px[y * pitch + x] = SHADE;
    line(px, w, h, pitch, 0, "SETTINGS", GOLD);
    for (int i = 0; i < v->n; i++) {                     /* (the chosen item gold, with the pointer) */
        char s[64];
        if (v->values[i][0]) snprintf(s, sizeof s, "%c %s: %s", i == v->at ? 0x7F : ' ', v->names[i], v->values[i]);
        else snprintf(s, sizeof s, "%c %s", i == v->at ? 0x7F : ' ', v->names[i]);
        line(px, w, h, pitch, 3 + 2 * i, s, i == v->at ? GOLD : WHITE);
    }
    line(px, w, h, pitch, 16, "Up / Down: choose", DIM);  /* (each line 42 letters at most: 256 pixels) */
    line(px, w, h, pitch, 17, "Enter or Left / Right: change", DIM);
    line(px, w, h, pitch, 18, "Esc or F9: close", DIM);
    line(px, w, h, pitch, 20, "Controller: d-pad or stick: choose", DIM);
    line(px, w, h, pitch, 21, "A or Start: change   Back: close", DIM);
    for (int y = 0; y < h; y++)                           /* (the text opaque: its colours carry no alpha) */
        for (int x = 0; x < w; x++)
            if (!(px[y * pitch + x] >> 24)) px[y * pitch + x] |= 0xFF000000u;
}
